const checks = [];
function check(name, condition, details = null) {
  checks.push({ name, passed: Boolean(condition), details });
  if (!condition) throw new Error(`${name}${details ? `: ${JSON.stringify(details)}` : ""}`);
}
function readJson(path) {
  return JSON.parse(fs.readFileSync(path, "utf8"));
}
function sha(path) {
  return crypto.createHash("sha256").update(fs.readFileSync(path)).digest("hex");
}
function commands(data) {
  const found = [];
  function visit(value, locator) {
    if (Array.isArray(value)) {
      value.forEach((item, index) => visit(item, `${locator}[${index}]`));
    } else if (value && typeof value === "object") {
      if (Number.isInteger(value.code) && Array.isArray(value.parameters)) {
        found.push({ locator, command: value });
      }
      for (const [key, item] of Object.entries(value)) visit(item, `${locator}.${key}`);
    }
  }
  visit(data, "$root");
  return found;
}
function scripts(path) {
  return commands(readJson(path))
    .filter(({ command }) => [355, 655].includes(command.code))
    .map(({ locator, command }) => ({ locator, text: String(command.parameters[0] || "") }));
}
function strictPlugins() {
  const path = "frontend/js/plugins.js";
  const source = fs.readFileSync(path, "utf8");
  check("plugins-envelope-prefix", source.startsWith("// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n["));
  check("plugins-envelope-suffix", source.endsWith("];\n"));
  const sandbox = {};
  vm.createContext(sandbox);
  vm.runInContext(source, sandbox, { filename: path, timeout: 1000 });
  check("plugins-array", Array.isArray(sandbox.$plugins));
  return sandbox.$plugins;
}
function decodeStructArray(raw) {
  return JSON.parse(raw).map(JSON.parse);
}

