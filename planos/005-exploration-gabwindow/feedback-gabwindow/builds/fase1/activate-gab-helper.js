"use strict";
const fs = require("fs");
const file = "frontend/js/plugins.js";
const source = fs.readFileSync(file, "utf8");
const prefix = "var $plugins =";
const marker = source.indexOf(prefix);
const start = source.indexOf("[", marker);
const end = source.lastIndexOf("]");
if (marker < 0 || start < 0 || end < start) throw new Error("Unexpected plugins.js envelope");
const plugins = JSON.parse(source.slice(start, end + 1));
if (plugins.some(plugin => plugin.name === "Coreto_GabWindowDefaults")) throw new Error("Helper already active");
const gabIndex = plugins.findIndex(plugin => plugin.name === "VisuMZ_4_GabWindow");
if (gabIndex < 0) throw new Error("GabWindow is inactive");
plugins.splice(gabIndex + 1, 0, {
  name: "Coreto_GabWindowDefaults",
  status: true,
  description: "[RPG Maker MZ] [Coreto] Gab Window defaults",
  parameters: { MapTargetGap: "8" }
});
fs.writeFileSync(file, "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins = " + JSON.stringify(plugins, null, 4) + ";\n", "utf8");
