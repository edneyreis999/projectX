import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = new URL("../../../../", import.meta.url);
const dataRoot = new URL("frontend/data/", root);

const fail = message => { throw new Error(message); };
const readText = relative => fs.readFileSync(new URL(relative, root), "utf8").replace(/^\uFEFF/, "");
const loadJson = relative => JSON.parse(readText(relative));
const sameValue = (actual, expected) => JSON.stringify(actual) === JSON.stringify(expected);

function requirePattern(source, pattern, message) {
    if (!pattern.test(source)) fail(message);
}

export function parsePluginsEnvelope(source) {
    const match = source.match(
        /^\uFEFF?\s*\/\/ Generated by RPG Maker\.\s*\r?\n\/\/ Do not edit this file directly\.\s*\r?\nvar \$plugins\s*=\s*(\[[\s\S]*\])\s*;\s*$/
    );
    if (!match) fail("plugins.js envelope must contain only the RPG Maker header and one $plugins JSON array");

    let plugins;
    try {
        plugins = JSON.parse(match[1]);
    } catch (error) {
        fail(`plugins.js array is not valid JSON: ${error.message}`);
    }
    if (!Array.isArray(plugins) || plugins.some(plugin =>
        !plugin || typeof plugin !== "object" || Array.isArray(plugin) ||
        typeof plugin.name !== "string" || typeof plugin.status !== "boolean" ||
        !plugin.parameters || typeof plugin.parameters !== "object" || Array.isArray(plugin.parameters)
    )) {
        fail("plugins.js must contain well-formed plugin objects");
    }
    return plugins;
}

function activePluginIndex(plugins, name) {
    const matches = plugins
        .map((plugin, index) => ({ plugin, index }))
        .filter(entry => entry.plugin.name === name && entry.plugin.status);
    if (matches.length !== 1) fail(`${name} must have exactly one active entry; found ${matches.length}`);
    return matches[0];
}

function parsePkdQuestDefinitions(pkdPlugin) {
    const serialized = pkdPlugin.parameters["sqsQuests:structA"];
    if (typeof serialized !== "string") fail("PKD sqsQuests:structA parameter is missing");

    let entries;
    try {
        entries = JSON.parse(serialized).map(entry => typeof entry === "string" ? JSON.parse(entry) : entry);
    } catch (error) {
        fail(`PKD quest definitions are not parseable: ${error.message}`);
    }
    if (!Array.isArray(entries)) fail("PKD quest definitions must be an array");
    return entries;
}

export function validatePluginConfiguration(plugins) {
    const pkd = activePluginIndex(plugins, "PKD_SimpleQuestSystem");
    const questCore = activePluginIndex(plugins, "Coreto_QuestCore");
    const questVn = activePluginIndex(plugins, "Coreto_QuestVN");
    const cutscene = activePluginIndex(plugins, "Coreto_Cutscene");

    if (!(pkd.index < questCore.index && questCore.index < questVn.index && questVn.index < cutscene.index)) {
        fail("active plugin order must be PKD -> Coreto_QuestCore -> Coreto_QuestVN -> Coreto_Cutscene");
    }

    const pkdDefinitions = parsePkdQuestDefinitions(pkd.plugin);
    const quest = pkdDefinitions.find(entry => entry?.id === "assistirNoiteHistoria");
    if (!quest) fail("PKD quest assistirNoiteHistoria is missing");

    let tasks;
    try {
        tasks = JSON.parse(quest["tasks:strA"]);
    } catch (error) {
        fail(`PKD assistirNoiteHistoria tasks are not parseable: ${error.message}`);
    }
    if (!Array.isArray(tasks) || tasks.length < 2) {
        fail("PKD assistirNoiteHistoria must expose at least two tasks");
    }

    return {
        activeIndexes: {
            PKD_SimpleQuestSystem: pkd.index,
            Coreto_QuestCore: questCore.index,
            Coreto_QuestVN: questVn.index,
            Coreto_Cutscene: cutscene.index
        },
        pkdQuestId: quest.id,
        pkdTaskCount: tasks.length
    };
}

export function validateRegistry(registry, system) {
    if (registry?.schemaVersion !== 1 || !registry.quests || typeof registry.quests !== "object") {
        fail("CoretoQuests registry schema is invalid");
    }

    const quest = registry.quests["noite-da-historia"];
    if (!quest) fail("registry quest noite-da-historia is missing");
    if (quest.stageVariableId !== 106 || system?.variables?.[106] !== "v_qNoiteDaHistoria_stage") {
        fail("noite-da-historia must use named stage variable V106");
    }
    if (quest.initialState !== 0 || !sameValue(quest.terminalStates, [90])) {
        fail("noite-da-historia initial and terminal states must be 0 and [90]");
    }

    const expectedTransitions = {
        START: { from: [0], to: 10 },
        COMPLETE_VN: { from: [10], to: 20 },
        ARRIVE_MAP045: { from: [20], to: 90 }
    };
    if (!sameValue(Object.keys(quest.transitions).sort(), Object.keys(expectedTransitions).sort())) {
        fail("noite-da-historia transition set is not exact");
    }

    const declaredStates = new Set([quest.initialState, ...quest.terminalStates]);
    for (const [transitionId, expected] of Object.entries(expectedTransitions)) {
        const transition = quest.transitions[transitionId];
        if (!sameValue(transition.from, expected.from) || transition.to !== expected.to ||
                !Array.isArray(transition.requirements) || !Array.isArray(transition.effects)) {
            fail(`registry transition ${transitionId} has an invalid state or payload shape`);
        }
        if (transition.effects.length > 0 && transition.receiptPolicy !== "once") {
            fail(`registry transition ${transitionId} effects require receiptPolicy once`);
        }
        transition.from.forEach(state => declaredStates.add(state));
        declaredStates.add(transition.to);
    }
    if (!sameValue([...declaredStates].sort((a, b) => a - b), [0, 10, 20, 90])) {
        fail("registry state table must be exactly 0, 10, 20, 90");
    }
    if (quest.transitions.ARRIVE_MAP045.terminal !== true) {
        fail("ARRIVE_MAP045 must be the terminal transition");
    }

    const expectedObjectives = [
        { id: 1, knownFrom: 10, completedAt: 10 },
        { id: 2, knownFrom: 10, completedAt: 20 }
    ];
    if (quest.pkd?.questId !== "assistirNoiteHistoria" ||
            !sameValue(quest.pkd.objectives, expectedObjectives)) {
        fail("registry PKD projection for assistirNoiteHistoria is invalid");
    }

    const questVn = quest.extensions?.questVN;
    const entry = questVn?.entries?.CENA_PRINCIPAL;
    if (questVn?.mapId !== 46 || entry?.eventId !== 1 || !sameValue(entry.allowedStates, [10])) {
        fail("registry VN entry CENA_PRINCIPAL must target Map046 event 1 from state 10");
    }

    return {
        questKey: "noite-da-historia",
        stageVariableId: quest.stageVariableId,
        stageVariableName: system.variables[106],
        states: [...declaredStates].sort((a, b) => a - b),
        transitions: Object.keys(quest.transitions),
        vnEntry: "CENA_PRINCIPAL"
    };
}

export function validateQuestCoreSource(source) {
    if (source.includes("VisuMZ_2_QuestSystem")) {
        fail("Coreto_QuestCore must not depend on VisuMZ_2_QuestSystem");
    }
    if (source.includes("$gameVariables.setValue(106")) {
        fail("Coreto_QuestCore must resolve the stage variable from the registry, not hard-code V106");
    }

    requirePattern(source, /@target MZ/, "Coreto_QuestCore MZ header is missing");
    for (const command of ["QuestTransition", "QuestSync", "AssertQuestState", "InspectQuestState"]) {
        requirePattern(source, new RegExp(`@command ${command}\\b`), `Coreto_QuestCore header command ${command} is missing`);
        requirePattern(
            source,
            new RegExp(`PluginManager\\.registerCommand\\(PLUGIN_NAME, "${command}"`),
            `Coreto_QuestCore runtime command ${command} is missing`
        );
    }

    requirePattern(
        source,
        /const Coreto = globalThis\.Coreto = globalThis\.Coreto \|\| \{\};/,
        "Coreto_QuestCore must preserve the accumulated Coreto namespace"
    );
    requirePattern(source, /globalThis\.SQSM/, "Coreto_QuestCore SQSM backend boundary is missing");
    for (const method of [
        "quests", "isQuestVisible", "isQuestComplete", "isQuestTaskVisible",
        "isQuestTaskComplete", "AddQuest", "ShowTaskForQuest", "CompleteTaskForQuest", "CompleteQuest"
    ]) {
        requirePattern(source, new RegExp(`"${method}"`), `Coreto_QuestCore does not validate SQSM.${method}`);
    }

    requirePattern(
        source,
        /if \(!api\.isQuestVisible\(questId\)\) api\.AddQuest\(questId\);/,
        "PKD AddQuest projection must be idempotent"
    );
    requirePattern(
        source,
        /if \(!api\.isQuestTaskVisible\(questId, objective\.id\)\)\s*\{\s*api\.ShowTaskForQuest\(questId, objective\.id\);\s*\}/,
        "PKD ShowTaskForQuest projection must be idempotent"
    );
    requirePattern(
        source,
        /current >= objective\.completedAt && !api\.isQuestTaskComplete\(questId, objective\.id\)/,
        "PKD CompleteTaskForQuest projection must be idempotent"
    );
    requirePattern(
        source,
        /if \(terminal && !api\.isQuestComplete\(questId\)\) api\.CompleteQuest\(questId\);/,
        "PKD CompleteQuest projection must be idempotent"
    );
    requirePattern(
        source,
        /\$gameVariables\.setValue\(quest\.stageVariableId, transitionDefinition\.to\);/,
        "QuestCore transition must write the registry-owned stage variable"
    );
    requirePattern(
        source,
        /DataManager\._databaseFiles\.push\(\{ name: DATABASE_NAME, src: DATABASE_SOURCE \}\);/,
        "CoretoQuests database registration is missing"
    );
    requirePattern(source, /Coreto\.QuestCore\s*=\s*\{[\s\S]*?FlowCoordinator[\s\S]*?\};/, "Coreto.QuestCore public API is incomplete");

    return {
        backend: "SQSM",
        visuQuestDependency: false,
        idempotentProjection: true,
        registryOwnedStageWrite: true,
        namespacePreserved: true
    };
}

function collectDirectV106Writers() {
    const hits = [];
    const candidates = fs.readdirSync(dataRoot, { withFileTypes: true })
        .filter(entry => entry.isFile() && /^(Map\d+|CommonEvents|Troops)\.json$/.test(entry.name));

    function visit(value, locator, file) {
        if (Array.isArray(value)) {
            value.forEach((child, index) => visit(child, `${locator}[${index}]`, file));
        } else if (value && typeof value === "object") {
            if (value.code === 122 && value.parameters?.[0] <= 106 && value.parameters?.[1] >= 106) {
                hits.push({ file, locator, parameters: value.parameters });
            }
            Object.entries(value).forEach(([key, child]) => visit(child, `${locator}.${key}`, file));
        }
    }

    for (const entry of candidates) {
        const source = fs.readFileSync(new URL(entry.name, dataRoot), "utf8").replace(/^\uFEFF/, "");
        visit(JSON.parse(source), "$", entry.name);
    }
    return hits;
}

export function validateArchitecture({ registry, system, pluginsSource, questCoreSource, directV106Writers = [] }) {
    const plugins = parsePluginsEnvelope(pluginsSource);
    const registrySummary = validateRegistry(registry, system);
    const pluginSummary = validatePluginConfiguration(plugins);
    const questCoreSummary = validateQuestCoreSource(questCoreSource);
    if (directV106Writers.length > 0) {
        fail(`event data must not write V106 directly: ${JSON.stringify(directV106Writers)}`);
    }
    return {
        validation: "structural_validation",
        registry: registrySummary,
        plugins: pluginSummary,
        questCore: questCoreSummary,
        directV106Writers: 0
    };
}

function run() {
    const result = validateArchitecture({
        registry: loadJson("frontend/data/CoretoQuests.json"),
        system: loadJson("frontend/data/System.json"),
        pluginsSource: readText("frontend/js/plugins.js"),
        questCoreSource: readText("frontend/js/plugins/Coreto_QuestCore.js"),
        directV106Writers: collectDirectV106Writers()
    });
    console.log("architecture static validation passed");
    console.log(JSON.stringify(result, null, 2));
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : null;
if (invokedPath === import.meta.url) run();
